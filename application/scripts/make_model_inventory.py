"""Generate application\\models\\MODEL_INVENTORY.md from models.json, real file sizes and the manifest.
Run from the suite root after `call ENV.bat` and AFTER make_manifest.py:
    python application\\scripts\\make_model_inventory.py
"""
import json
import sys
from pathlib import Path

SUITE_ROOT = Path(__file__).resolve().parents[2]
APP = SUITE_ROOT / "application"
sys.path.insert(0, str(APP / "scripts"))
import make_manifest as mm  # noqa: E402

# Measured by llm_check.py on the preparation PC (i5-1135G7, 16 GB, cpu_16gb profile).
# Single runs. Treat as indicative, not a benchmark.
MEASURED = {
    "qwen3-4b": "8.3-12.3 tok/s",
    "google-gemma-3-4b-it": "9.7 tok/s",
    "qwen3-8b": "4.4-5.1 tok/s",
    "qwen2.5-coder-7b": "4.4-6.0 tok/s",
    "sqlcoder-7b": "7.3 tok/s (completion mode)",
    "deepseek-r1-distill-7b": "6.2 tok/s (load test only)",
    "llama-3.2-3b": "12.1 tok/s (failed the strict-instruction check)",
    "bge-m3": "n/a (embedding, 1024 dims)",
}


def main():
    models = json.loads((APP / "models" / "models.json").read_text(encoding="utf-8"))["models"]
    try:
        entries = mm.read_manifest()
    except FileNotFoundError:
        print("No manifest. Run make_manifest.py first.")
        return 1
    out = ["# Model inventory", "",
           "Generated by application/scripts/make_model_inventory.py. Do not edit by hand.", "",
           "Verification: file exists, starts with GGUF magic bytes, loads in llama-server and answers "
           "(application/scripts/llm_check.py). Licences are from memory: see LICENSES/THIRD_PARTY.md.", "",
           "| id | file | size GB | SHA-256 | family | quant | kind | roles | default for | est. RAM GB | measured speed | licence (verify) |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for m in models:
        rel = f"application/models/{m['file']}"
        digest, size = entries.get(rel, ("NOT IN MANIFEST", 0))
        out.append("| {id} | {file} | {size:.2f} | {sha} | {family} | {quant} | {kind} | {roles} | {dflt} | {ram} | {speed} | {lic} |".format(
            id=m["id"], file=m["file"], size=size / 1e9, sha=digest, family=m.get("family", ""),
            quant=m.get("quant", ""), kind=m.get("kind", "chat"), roles=", ".join(m.get("roles", [])) or "none",
            dflt=", ".join(m.get("default_for", [])) or "none", ram=m.get("ram_gb_est", "?"),
            speed=MEASURED.get(m["id"], "not measured"), lic=m.get("license", "verify")))
    out += ["", "## Notes", "",
            "- Defaults are placeholders until the Project 1 and Project 2 benchmarks run.",
            "- DeepSeek-R1-Distill puts its answer inside long thinking text. Optional, no default role.",
            "- Llama 3.2 3B ignored a strict one-word instruction. No role assigned.",
            "- SQLCoder needs its own prompt format via /completion and may emit PostgreSQL-style SQL and a stray [SQL] marker.",
            "- Qwen3 models run with thinking disabled through chat_template_kwargs (no_think flag).",
            "- Only one model is loaded at a time. Split GGUF files must stay together."]
    target = APP / "models" / "MODEL_INVENTORY.md"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("Written:", target)
    return 0


if __name__ == "__main__":
    sys.exit(main())